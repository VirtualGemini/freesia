-- Unreleased baseline: maintain one V1 per language, not new migration versions for development steps.
-- Fresh installations only; select exactly one baseline with FREESIA_DB_LANGUAGE=zh/en.
-- Switching scripts cannot translate an existing database; no legacy data, accounts or credentials are seeded.
CREATE SCHEMA IF NOT EXISTS freesia;
COMMENT ON SCHEMA freesia IS 'Freesia business schema; Flyway history remains in public.';

-- Identity and access management: IAM owns accounts, profiles, roles, menus and authentication policies.
-- Accounts and password credentials; bootstrap-admin explicitly creates the first administrator.
-- Organizations have no enable/disable status; they carry the tree and data scope.
CREATE TABLE freesia.sys_organization (
    id uuid DEFAULT uuidv7() PRIMARY KEY,
    parent_id uuid REFERENCES freesia.sys_organization(id),
    code varchar(80) NOT NULL UNIQUE,
    name varchar(100) NOT NULL,
    remark varchar(500),
    sort integer NOT NULL DEFAULT 0,
    is_root boolean NOT NULL DEFAULT false,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CHECK (id IS DISTINCT FROM parent_id),
    CHECK (length(btrim(code)) BETWEEN 1 AND 80 AND length(btrim(name)) BETWEEN 1 AND 100),
    CHECK (is_root = (parent_id IS NULL))
);
COMMENT ON TABLE freesia.sys_organization IS 'Organization tree and data scope carrier; no status; root reserved for the initial owner.';
COMMENT ON COLUMN freesia.sys_organization.id IS 'Organization ID generated by PostgreSQL uuidv7().';
COMMENT ON COLUMN freesia.sys_organization.parent_id IS 'Parent organization; only the unique root has no parent; no self-reference or cycles.';
COMMENT ON COLUMN freesia.sys_organization.code IS 'Stable unique code; ROOT is reserved.';
COMMENT ON COLUMN freesia.sys_organization.name IS 'Organization display name.';
COMMENT ON COLUMN freesia.sys_organization.remark IS 'Optional remark, up to 500 characters.';
COMMENT ON COLUMN freesia.sys_organization.sort IS 'Sibling order with UUID as the tie breaker.';
COMMENT ON COLUMN freesia.sys_organization.is_root IS 'Exclusive root marker, not an organization status.';
COMMENT ON COLUMN freesia.sys_organization.created_at IS 'Creation timestamp with time zone.';
COMMENT ON COLUMN freesia.sys_organization.updated_at IS 'Last update timestamp maintained by write use cases.';
CREATE UNIQUE INDEX uk_organization_root ON freesia.sys_organization(is_root) WHERE is_root;
COMMENT ON INDEX freesia.uk_organization_root IS 'Allows at most one exclusive root.';
INSERT INTO freesia.sys_organization(code,name,is_root) VALUES ('ROOT','Root organization',true);

CREATE TABLE freesia.sys_account (
    id uuid DEFAULT uuidv7() PRIMARY KEY,
    username varchar(50) NOT NULL,
    organization_id uuid REFERENCES freesia.sys_organization(id),
    remark varchar(500),
    password_hash text NOT NULL,
    enabled boolean NOT NULL DEFAULT true,
    deleted boolean NOT NULL DEFAULT false,
    deleted_at timestamptz,
    must_change_password boolean NOT NULL DEFAULT false,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CHECK (username = btrim(username) AND length(username) BETWEEN 3 AND 50),
    CHECK (password_hash LIKE '$argon2id$%')
);
COMMENT ON TABLE freesia.sys_account IS 'Accounts and password credentials; bootstrap-admin explicitly creates the first administrator.';
COMMENT ON COLUMN freesia.sys_account.id IS 'Account primary key generated by PostgreSQL uuidv7().';
